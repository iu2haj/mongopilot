"""Schema analysis of sampled documents, similar to the Schema tab of MongoDB Compass.

Pure Python: works on documents decoded by pymongo (bson types are recognised by class name, so this module does not
import bson) and on the plain documents generated by the demo.
"""

from __future__ import annotations

import base64
import datetime as dt
import math
from collections import Counter
from typing import Any

TOP_VALUES = 12
MAX_DISTINCT = 1000        # distinct values tracked per field before counting stops (keeps memory bounded)
HISTOGRAM_BINS = 20
MAX_DEPTH = 12


def bson_type(v: Any) -> str:
    """Type name as Compass shows it."""
    if v is None:
        return "Null"
    if isinstance(v, bool):
        return "Boolean"
    name = type(v).__name__
    if name == "Int64":
        return "Int64"
    if isinstance(v, int):
        return "Int32" if -2**31 <= v < 2**31 else "Int64"
    if isinstance(v, float):
        return "Double"
    if isinstance(v, str):
        return "String"
    if isinstance(v, dt.datetime):
        return "Date"
    if isinstance(v, (list, tuple)):
        return "Array"
    if isinstance(v, dict):
        return "Document"
    return {
        "ObjectId": "ObjectId", "Decimal128": "Decimal128", "Timestamp": "Timestamp", "Regex": "Regex",
        "Pattern": "Regex", "UUID": "UUID", "Code": "Code", "MinKey": "MinKey", "MaxKey": "MaxKey",
        "DBRef": "DBRef", "Binary": "Binary", "bytes": "Binary", "SON": "Document", "RawBSONDocument": "Document",
    }.get(name, name)


NUMERIC = {"Int32", "Int64", "Double", "Decimal128"}


def display(v: Any, limit: int = 120) -> Any:
    """JSON-safe representation of a value for the UI."""
    t = bson_type(v)
    if t in ("Int32", "Int64", "Double", "Boolean", "Null"):
        if isinstance(v, float) and (math.isnan(v) or math.isinf(v)):
            return str(v)
        return v
    if t == "String":
        return v if len(v) <= limit else v[:limit] + "…"
    if t == "Date":
        return _iso(v)
    if t == "Binary":
        raw = bytes(v)
        return "base64:" + base64.b64encode(raw[:48]).decode() + ("…" if len(raw) > 48 else "")
    return str(v)[:limit]


def _iso(d: dt.datetime) -> str:
    if d.tzinfo is None:
        d = d.replace(tzinfo=dt.timezone.utc)
    return d.astimezone(dt.timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")


def _ts(d: dt.datetime) -> float:
    return (d if d.tzinfo else d.replace(tzinfo=dt.timezone.utc)).timestamp()


def _number(v: Any) -> float | None:
    try:
        f = float(str(v)) if bson_type(v) == "Decimal128" else float(v)
    except (TypeError, ValueError):
        return None
    return f if math.isfinite(f) else None


class _TypeAcc:
    def __init__(self, name: str):
        self.name = name
        self.count = 0
        self.values: Counter = Counter()
        self.distinct_overflow = False
        self.numbers: list[float] = []        # numbers, string lengths, timestamps, array lengths
        self.lengths: list[int] = []
        self.weekdays = [0] * 7
        self.hours = [0] * 24
        self.element: _FieldAcc | None = None  # arrays: statistics of their elements
        self.children: dict[str, _FieldAcc] = {}  # documents: their fields

    def add(self, v: Any, path: str, depth: int) -> None:
        self.count += 1
        t = self.name
        if t in ("Document", "Array"):
            pass
        elif len(self.values) < MAX_DISTINCT or _key(v) in self.values:
            self.values[_key(v)] += 1
        else:
            self.distinct_overflow = True
        if t in NUMERIC:
            n = _number(v)
            if n is not None:
                self.numbers.append(n)
        elif t == "String":
            self.lengths.append(len(v))
        elif t == "Date":
            self.numbers.append(_ts(v))
            d = v if v.tzinfo else v.replace(tzinfo=dt.timezone.utc)
            self.weekdays[d.weekday()] += 1
            self.hours[d.hour] += 1
        elif t == "ObjectId":
            gt = getattr(v, "generation_time", None)
            if gt is not None:
                self.numbers.append(_ts(gt))
        elif t == "Array":
            self.lengths.append(len(v))
            if depth < MAX_DEPTH:
                if self.element is None:
                    self.element = _FieldAcc(path, "[]")
                for item in v:
                    self.element.add(item, depth + 1)
        elif t == "Document" and depth < MAX_DEPTH:
            for k, sub in v.items():
                acc = self.children.get(k)
                if acc is None:
                    acc = self.children[k] = _FieldAcc(f"{path}.{k}" if path else k, k)
                acc.add(sub, depth + 1)

    def result(self, parent_count: int) -> dict[str, Any]:
        out: dict[str, Any] = {"name": self.name, "count": self.count,
                               "probability": round(self.count / parent_count, 4) if parent_count else 0}
        if self.name not in ("Document", "Array"):
            top = self.values.most_common(TOP_VALUES)
            out["top_values"] = [{"value": _unkey(k), "count": c} for k, c in top]
            out["distinct"] = len(self.values)
            out["distinct_capped"] = self.distinct_overflow
            out["unique"] = not self.distinct_overflow and len(self.values) == self.count and self.count > 1
        if self.name in NUMERIC and self.numbers:
            out.update(_numeric_stats(self.numbers))
        if self.name == "String" and self.lengths:
            out["min_length"], out["max_length"] = min(self.lengths), max(self.lengths)
            out["avg_length"] = round(sum(self.lengths) / len(self.lengths), 1)
        if self.name in ("Date", "ObjectId") and self.numbers:
            lo, hi = min(self.numbers), max(self.numbers)
            out["min"] = _iso(dt.datetime.fromtimestamp(lo, dt.timezone.utc))
            out["max"] = _iso(dt.datetime.fromtimestamp(hi, dt.timezone.utc))
            out["histogram"] = _histogram(self.numbers, time_axis=True)
            if self.name == "Date":
                out["weekdays"], out["hours"] = self.weekdays, self.hours
        if self.name == "Boolean":
            out["true"] = self.values.get(_key(True), 0)
            out["false"] = self.values.get(_key(False), 0)
        if self.name == "Array" and self.lengths:
            out["min_length"], out["max_length"] = min(self.lengths), max(self.lengths)
            out["avg_length"] = round(sum(self.lengths) / len(self.lengths), 2)
            if self.element is not None and self.element.count:
                out["element"] = self.element.result(self.element.count)
                out["element"]["total"] = self.element.count
        if self.name == "Document":
            out["fields"] = _fields_result(self.children, self.count)
        return out


class _FieldAcc:
    def __init__(self, path: str, name: str):
        self.path, self.name = path, name
        self.count = 0
        self.types: dict[str, _TypeAcc] = {}

    def add(self, v: Any, depth: int) -> None:
        self.count += 1
        t = bson_type(v)
        acc = self.types.get(t)
        if acc is None:
            acc = self.types[t] = _TypeAcc(t)
        acc.add(v, self.path, depth)

    def result(self, parent_count: int) -> dict[str, Any]:
        types = sorted(self.types.values(), key=lambda a: -a.count)
        missing = parent_count - self.count
        return {
            "path": self.path, "name": self.name, "count": self.count,
            "probability": round(self.count / parent_count, 4) if parent_count else 0,
            "missing": max(0, missing),
            "types": [a.result(self.count) for a in types],
        }


def _fields_result(children: dict[str, _FieldAcc], parent_count: int) -> list[dict[str, Any]]:
    rows = [acc.result(parent_count) for acc in children.values()]
    # _id first, then the order in which fields were first seen (like Compass)
    rows.sort(key=lambda r: 0 if r["name"] == "_id" else 1)
    return rows


def _key(v: Any) -> Any:
    """Hashable, type-preserving key for value counting."""
    t = bson_type(v)
    return (t, display(v))


def _unkey(k: Any) -> Any:
    return k[1]


def _numeric_stats(nums: list[float]) -> dict[str, Any]:
    nums_sorted = sorted(nums)
    n = len(nums_sorted)
    mean = sum(nums_sorted) / n
    median = nums_sorted[n // 2] if n % 2 else (nums_sorted[n // 2 - 1] + nums_sorted[n // 2]) / 2
    return {"min": nums_sorted[0], "max": nums_sorted[-1], "mean": round(mean, 4), "median": median,
            "histogram": _histogram(nums_sorted)}


def _histogram(values: list[float], time_axis: bool = False) -> dict[str, Any]:
    lo, hi = min(values), max(values)
    if hi == lo:
        return {"lo": lo, "hi": hi, "bins": [len(values)], "time": time_axis}
    bins = [0] * HISTOGRAM_BINS
    width = (hi - lo) / HISTOGRAM_BINS
    for v in values:
        bins[min(HISTOGRAM_BINS - 1, int((v - lo) / width))] += 1
    return {"lo": lo, "hi": hi, "bins": bins, "time": time_axis}


def analyze(docs: list[dict[str, Any]]) -> dict[str, Any]:
    """Field-by-field statistics of a list of documents."""
    root: dict[str, _FieldAcc] = {}
    for doc in docs:
        for k, v in doc.items():
            acc = root.get(k)
            if acc is None:
                acc = root[k] = _FieldAcc(k, k)
            acc.add(v, 1)
    fields = _fields_result(root, len(docs))
    return {"sampled": len(docs), "fields": fields, "field_count": _count_fields(fields)}


def _count_fields(fields: list[dict[str, Any]]) -> int:
    total = 0
    for f in fields:
        total += 1
        for t in f["types"]:
            total += _count_fields(t.get("fields", []))
            el = t.get("element")
            if el:
                for et in el["types"]:
                    total += _count_fields(et.get("fields", []))
    return total
